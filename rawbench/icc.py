"""Small matrix/shaper ICC profile used to tag Display P3 exports."""
from __future__ import annotations

import datetime
import struct

import numpy as np

D50 = np.array([0.96422, 1, 0.82521])
D65 = np.array([0.95047, 1, 1.08883])
BRADFORD = np.array([
    [0.8951, 0.2664, -0.1614],
    [-0.7502, 1.7135, 0.0367],
    [0.0389, -0.0685, 1.0296],
])
P3_XY = ((0.680, 0.320), (0.265, 0.690), (0.150, 0.060))
SRGB_TRANSFER = (2.4, 1 / 1.055, 0.055 / 1.055, 1 / 12.92, 0.04045, 0, 0)


def _fixed(value: float) -> bytes:
    return struct.pack(">i", round(float(value) * 65536))


def _u32(value: int) -> bytes:
    return struct.pack(">I", value)


def _type(identifier: bytes) -> bytes:
    return identifier + b"\x00" * 4


def _fixed_vector(values) -> bytes:
    return b"".join(_fixed(value) for value in values)


def _xyz_type(values) -> bytes:
    return _type(b"XYZ ") + _fixed_vector(values)


def _matrix_type(values: np.ndarray) -> bytes:
    return _type(b"sf32") + _fixed_vector(values.ravel())


def _localized_text(value: str, *, language: bytes = b"en", country: bytes = b"US") -> bytes:
    chars = value.encode("utf-16-be")
    record = language + country + _u32(len(chars)) + _u32(28)
    return _type(b"mluc") + _u32(1) + _u32(12) + record + chars


def _parametric_curve(values) -> bytes:
    return _type(b"para") + struct.pack(">HH", 4, 0) + _fixed_vector(values)


def _adaptation(source: np.ndarray, target: np.ndarray) -> np.ndarray:
    ratio = (BRADFORD @ target) / (BRADFORD @ source)
    return np.linalg.inv(BRADFORD) @ np.diag(ratio) @ BRADFORD


def _columns(primaries: tuple[tuple[float, float], ...], white: np.ndarray) -> np.ndarray:
    relative = np.array([(x / y, 1.0, (1 - x - y) / y) for x, y in primaries]).T
    scales = np.linalg.solve(relative, white)
    return relative * scales


def _header(size: int) -> bytes:
    when = datetime.datetime(2020, 1, 1)
    date = struct.pack(">6H", when.year, when.month, when.day, when.hour, when.minute, when.second)
    content = (
        _u32(size) + b"    " + b"\x04\x30\x00\x00"
        + b"mntrRGB XYZ " + date + b"acsp" + b"APPL"
        + _u32(0) + b"    " + b"    " + b"\x00" * 8
        + _u32(1) + _fixed_vector(D50) + b"mscL"
        + b"\x00" * 16 + b"\x00" * 28
    )
    if len(content) != 128:
        raise ValueError("Invalid ICC header size.")
    return content


def _tag_table(tags: list[tuple[bytes, bytes]]) -> tuple[bytes, bytes]:
    offset = 128 + 4 + 12 * len(tags)
    table = [_u32(len(tags))]
    data = []
    offsets = {}
    for name, content in tags:
        if content not in offsets:
            offsets[content] = offset
            padded = content + b"\x00" * ((-len(content)) % 4)
            data.append(padded)
            offset += len(padded)
        table.append(name + _u32(offsets[content]) + _u32(len(content)))
    return b"".join(table), b"".join(data)


def display_p3_icc() -> bytes:
    adapt = _adaptation(D65, D50)
    cols = adapt @ _columns(P3_XY, D65)
    curve = _parametric_curve(SRGB_TRANSFER)
    tags = [
        (b"desc", _localized_text("MosaicLab Display P3")),
        (b"cprt", _localized_text("Generated by MosaicLab")),
        (b"wtpt", _xyz_type(D50)),
        (b"chad", _matrix_type(adapt)),
        (b"rXYZ", _xyz_type(cols[:, 0])),
        (b"gXYZ", _xyz_type(cols[:, 1])),
        (b"bXYZ", _xyz_type(cols[:, 2])),
        (b"rTRC", curve),
        (b"gTRC", curve),
        (b"bTRC", curve),
    ]
    table, data = _tag_table(tags)
    return _header(128 + len(table) + len(data)) + table + data
